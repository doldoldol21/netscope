  // ?lang=xx wins (testing), then the system language the webview reports.
  const qs = new URLSearchParams(location.search).get("lang");
  const sys = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
  const base = String(qs || sys).toLowerCase().split(/[-_]/)[0];
  const lang = Object.prototype.hasOwnProperty.call(dicts, base) ? base : "en";
  document.documentElement.lang = lang;

  function t(key, vars) {
    let s = dicts[lang][key];
    if (s === undefined) s = dicts.en[key];
    if (s === undefined) return key;
    if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
    return s;
  }
  // tn picks the singular or plural key by n (no plural in ko/ja — both keys
  // simply hold the same string there) and interpolates {n} plus vars.
  function tn(key1, keyN, n, vars) {
    return t(n === 1 ? key1 : keyN, Object.assign({ n }, vars));
  }

  // Apply translations to the static HTML that opted in via data-i18n-* attrs.
  function apply(root) {
    const r = root || document;
    r.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    r.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    r.querySelectorAll("[data-i18n-tip]").forEach((el) => { el.setAttribute("data-tip", t(el.dataset.i18nTip)); });
    r.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  }
  apply(); // the script sits at the end of <body>, so the DOM above is parsed

  return { t, tn, lang, apply };
